std::string resolveAsset(const std::string& value, const AssetDatabase* assets,
                         const std::string& entity, const std::string& comp,
                         const std::string& prop, Diagnostics& diag) {
    if (!assets) return value;
    const AssetGuid g = AssetDatabase::parseRef(value);
    if (!g.valid()) return value;

    const AssetRecord* rec = assets->find(g);
    if (!rec || rec->missing) {
        diag.error("entity '" + entity + "': " + comp + "." + prop
                   + " points at a missing asset"
                   + (rec ? " (was " + rec->relPath + ")" : "")
                   + " [" + g.str() + "]");
        return "nil";
    }
    const std::string path = "content/" + rec->relPath;
    std::string q = "\"";
    for (char c : path) {
        if (c == '"' || c == '\\') q += '\\';
        q += c;
    }
    return q + "\"";
}

