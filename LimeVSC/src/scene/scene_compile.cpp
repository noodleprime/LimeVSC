bool isIdent(const std::string& s) {
    if (s.empty()) return false;
    if (!std::isalpha(static_cast<unsigned char>(s[0])) && s[0] != '_') return false;
    for (char c : s)
        if (!std::isalnum(static_cast<unsigned char>(c)) && c != '_') return false;
    static const char* kReserved[] = {
        "and", "break", "do", "else", "elseif", "end", "false", "for",
        "function", "goto", "if", "in", "local", "nil", "not", "or",
        "repeat", "return", "then", "true", "until", "while"};
    for (const char* r : kReserved)
        if (s == r) return false;
    return true;
}

std::string key(const std::string& k) {
    if (isIdent(k)) return k;
    std::string q = "[\"";
    for (char c : k) {
        if (c == '"' || c == '\\') q += '\\';
        q += c;
    }
    return q + "\"]";
}

std::string quote(const std::string& s) {
    std::string q = "\"";
    for (char c : s) {
        if (c == '"' || c == '\\') q += '\\';
        if (c == '\n') { q += "\\n"; continue; }
        q += c;
    }
    return q + "\"";
}

std::string moduleFromGraphRef(std::string ref) {
    for (char& c : ref)
        if (c == '\\') c = '/';
    if (ref.size() > 5 && ref.compare(ref.size() - 5, 5, ".lime") == 0)
        ref.resize(ref.size() - 5);
    while (!ref.empty() && (ref.front() == '/' || ref.front() == '.'))
        ref.erase(ref.begin());
    if (ref.rfind("content/", 0) != 0) ref = "content/" + ref;
    for (char& c : ref)
        if (c == '/') c = '.';
    return ref;
}

